// Function to write data to AD9833
void AD9833_Write(uint16_t data) {
    HAL_GPIO_WritePin(AD9833_FSYNC_PORT, AD9833_FSYNC_PIN, GPIO_PIN_RESET); // FSYNC Low
    uint8_t highByte = (data >> 8) & 0xFF;
    uint8_t lowByte = data & 0xFF;
    HAL_SPI_Transmit(&hspi1, &highByte, 1, HAL_MAX_DELAY); // Send high byte
    HAL_SPI_Transmit(&hspi1, &lowByte, 1, HAL_MAX_DELAY);  // Send low byte
    HAL_GPIO_WritePin(AD9833_FSYNC_PORT, AD9833_FSYNC_PIN, GPIO_PIN_SET);   // FSYNC High
}

// Function to initialize the AD9833
void AD9833_Init(void) {
    AD9833_Write(0x0100);
    AD9833_Write(0x2100); // Reset the AD9833 and set it to sine wave mode
}

// Function to set frequency
void AD9833_SetFrequency(double freq) {
    uint32_t freqWord = (uint32_t)((freq * (1 << 28)) / 25000000); // Calculate frequency word
    uint16_t freqLsb = (freqWord & 0x3FFF);          // Lower 14 bits
    uint16_t freqMsb = ((freqWord >> 14) & 0x3FFF);  // Upper 14 bits

    AD9833_Write(0x4000 | freqLsb); // Write lower 14 bits to frequency register
    AD9833_Write(0x4000 | freqMsb); // Write upper 14 bits to frequency register
}

// Function to start generating a sine wave
void AD9833_Start(void) {
    AD9833_Write(0x2000); // Exit reset mode and enable sine wave output
}
