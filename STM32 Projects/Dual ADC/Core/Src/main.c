 // This function processes the raw DMA data and separates it into two arrays.
 // The data from the two ADCs is concatenated by the hardware into a single
 // 32-bit word: [ADC2_Result (MSB 16 bits) | ADC1_Result (LSB 16 bits)].

void Extract_Inputs(float* sig1, float* sig2, uint32_t* raw)
{
    for (int i = 0; i < FFT_SIZE; i++) {
        sig1[i] = (float)(raw[i] & 0x0000FFFF);  // Correctly writes to inputSignal1
        sig2[i] = (float)(raw[i] >> 16);         // Correctly writes to inputSignal2
    }
}

void SendCSV(float* sig1, float* sig2, uint32_t* raw)
{
    //int i = 0;

    for (int i = 1; i <10; i++)    {
        int freq = i + 5;

        int n = snprintf(usbLineBuf, sizeof(usbLineBuf),
                         "%d, %d\r\n",
                         freq, i);

        // Try to transmit only if USB is ready
        while (CDC_Transmit_FS((uint8_t*)usbLineBuf, n) == USBD_BUSY) { }
        HAL_Delay(200);           // i++;  // move to next value ONLY if sent successfully
         // small delay to avoid flooding USB
    }
    // Optional header (send once if you want)
    int n = snprintf(usbLineBuf, sizeof(usbLineBuf),
                     "Index, Sig1, Sig2, Raw\r\n");
    while (CDC_Transmit_FS((uint8_t*)usbLineBuf, n) == USBD_BUSY) { }
    HAL_Delay(50);

    for (int i = 0; i < 150; i++)
    {
        n = snprintf(usbLineBuf, sizeof(usbLineBuf),
                     "%d, %.2f, %.2f, %lu\r\n",
                     i,
                     sig1[i],
                     sig2[i],
                     raw[i]);

        while (CDC_Transmit_FS((uint8_t*)usbLineBuf, n) == USBD_BUSY) { }

        HAL_Delay(5);  // keep this small but necessary
    }
}
